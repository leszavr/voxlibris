interface PolicyModalProps {
  isOpen: boolean;
  onClose: () => void;
  policyType: PolicyType;
}

export const PolicyModal: FC<PolicyModalProps> = ({
  isOpen,
  onClose,
  policyType,
}) => {
  const { title, content } = useMemo(() => POLICIES[policyType], [policyType]);

  useEffect(() => {
    if (!isOpen) {
      return;
    }

    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    const handleKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") {
        onClose();
      }
    };

    window.addEventListener("keydown", handleKeyDown);

    return () => {
      document.body.style.overflow = previousOverflow;
      window.removeEventListener("keydown", handleKeyDown);
    };
  }, [isOpen, onClose]);

  const normalizeInlineMarkdown = (text: string) => text.replace(/\*\*(.*?)\*\*/g, "$1");

  if (!isOpen) {
    return null;
  }

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-background/60 px-3 py-3 backdrop-blur-sm sm:px-4 sm:py-4"
      role="dialog"
      aria-modal="true"
      aria-labelledby="policy-modal-title"
      onMouseDown={(event) => {
        if (event.target === event.currentTarget) {
          onClose();
        }
      }}
    >
      <div className="flex h-[calc(100dvh-1.5rem)] w-full max-w-3xl flex-col overflow-hidden rounded-2xl border border-border bg-card/95 shadow-2xl sm:h-[calc(100dvh-2rem)]">
        <div className="flex items-start justify-between gap-3 border-b px-4 py-4 sm:px-6">
          <div className="min-w-0">
            <h2 id="policy-modal-title" className="text-xl font-semibold tracking-tight sm:text-2xl">
              {title}
            </h2>
          </div>

          <Button variant="ghost" size="icon" onClick={onClose} className="shrink-0">
            <X className="h-4 w-4" />
            <span className="sr-only">Закрыть</span>
          </Button>
        </div>

        <ScrollArea className="min-h-0 flex-1">
          <div className="space-y-4 px-4 py-4 text-sm leading-relaxed sm:px-6 sm:py-5">
            {content.split("\n\n").map((paragraph, idx) => {
              const cleanText = normalizeInlineMarkdown(paragraph);

              if (paragraph.startsWith("##")) {
                const level = paragraph.match(/^#+/)?.[0].length ?? 2;
                const text = normalizeInlineMarkdown(paragraph.replace(/^#+\s/, ""));
                const headingClass =
                  level === 2
                    ? "mt-4 text-lg font-bold text-foreground first:mt-0"
                    : "mt-3 text-base font-semibold text-foreground first:mt-0";

                return (
                  <h3 key={idx} className={headingClass}>
                    {text}
                  </h3>
                );
              }

              if (paragraph.startsWith("-")) {
                return (
                  <ul key={idx} className="list-disc space-y-1 pl-5">
                    {paragraph.split("\n").map((item, itemIdx) => {
                      if (!item.startsWith("-")) return null;
                      const text = normalizeInlineMarkdown(item.replace(/^[-*]\s/, ""));

                      return (
                        <li key={itemIdx}>
                          {text}
                        </li>
                      );
                    })}
                  </ul>
                );
              }

              if (/^\d+\./.test(paragraph)) {
                return (
                  <ol key={idx} className="list-decimal space-y-1 pl-5">
                    {paragraph.split("\n").map((item, itemIdx) => {
                      if (!/^\d+\./.test(item)) return null;
                      const text = normalizeInlineMarkdown(item.replace(/^\d+\.\s/, ""));

                      return (
                        <li key={itemIdx}>
                          {text}
                        </li>
                      );
                    })}
                  </ol>
                );
              }

              return (
                <p key={idx} className="text-foreground">
                  {cleanText}
                </p>
              );
            })}
          </div>
        </ScrollArea>
      </div>
    </div>
  );
};
